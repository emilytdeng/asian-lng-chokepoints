/**
 * LP extension analysis (stage 6): fleet constraint, shadow prices, dual-driven investment ranking,
 * selective passage through Hormuz, and the 2026 validation comparison.
 * Writes results/findings_lp.md and results/lp_*.csv. Run via `npm run analysis`.
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import raw from "../data/network.json";
import { applyChanges } from "../src/model/graph";
import { fleetCapacity, lpFleetNeeded, lpLambda, lpLastInLine, lpOutbid, lpPriority } from "../src/model/lp";
import type { Network, Scenario } from "../src/model/types";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "results");
const NET = raw as unknown as Network;
const ORDER = ["JPN", "KOR", "TWN", "CHN", "THA", "IND", "BGD", "PAK"];
const pct = (x: number) => `${Math.round(Math.max(0, 100 * x))}%`;
const sgn = (x: number) => `${x >= 0 ? "+" : "−"}${Math.abs(Math.round(x))}%`;
const md = (h: string[], rows: (string | number)[][]) => [`| ${h.join(" | ")} |`, `|${h.map(() => "---").join("|")}|`, ...rows.map((r) => `| ${r.join(" | ")} |`)].join("\n");
const csv = (file: string, h: string[], rows: (string | number)[][]) => writeFileSync(join(OUT, file), [h.join(","), ...rows.map((r) => r.map((v) => (typeof v === "number" ? +v.toFixed(5) : /[",]/.test(v) ? `"${v}"` : v)).join(","))].join("\n") + "\n");
const name = (id: string) => NET.importers.find((i) => i.id === id)?.name ?? id;

async function views(net: Network, sc: Scenario) {
  const lam = (await lpLambda(net, { scenario: sc })).lambda!;
  const prio = await lpPriority(net, ORDER, { scenario: sc });
  const rows = [];
  for (const im of net.importers) {
    const d = im.import_demand.value;
    rows.push({ id: im.id, priority: prio[im.id] / d, rationed: lam, last: (await lpLastInLine(net, im.id, { scenario: sc })) / d, outbid: (await lpOutbid(net, im.id, { scenario: sc })) / d });
  }
  return { lam, rows };
}

async function main() {
  const L: string[] = ["# LP extension: fleet, shadow prices, selective passage, 2026 validation", "",
    "Generated by `npm run analysis` (scripts/analysis_lp.ts) with HiGHS. With the extras off, the LP reproduces the max-flow results exactly (tests/lp.test.ts).", ""];

  // ---------------------------------------------------------------- 1. fleet
  const cap0 = await fleetCapacity(NET);
  const fleetRows: (string | number)[][] = [];
  const baseNeed = (await lpFleetNeeded(NET, { scenario: NET.scenarios.baseline })).needed;
  for (const [, sc] of Object.entries(NET.scenarios)) {
    const need = { ...(await lpFleetNeeded(NET, { scenario: sc })) };
    need.baseline = baseNeed;
    const l = await lpLambda(NET, { scenario: { ...sc, fleet: true } });
    const binds = l.lambda! < need.lambda - 1e-6;
    fleetRows.push([sc.label, `${need.needed >= need.baseline ? "+" : "−"}${Math.abs(Math.round(100 * (need.needed / need.baseline - 1)))}%`, pct(need.needed / need.capacity), pct(need.lambda), pct(l.lambda!), binds ? "cuts supply" : "enough ships"]);
  }
  // how little spare fleet does it take before ships bind?
  const sweep: (string | number)[][] = [];
  for (const slack of [0, 0.05, 0.1, 0.2]) for (const dayF of [1, 1.25]) {
    const n: Network = structuredClone(NET);
    n.meta.fleet_slack!.value = slack;
    for (const l of n.links) if (l.voyage_days) l.voyage_days.value *= dayF;
    const row: (string | number)[] = [pct(slack), dayF === 1 ? "as estimated" : "+25% all legs"];
    for (const k of ["hormuz", "redsea", "malacca", "hormuz_redsea"]) {
      const l = await lpLambda(n, { scenario: { ...n.scenarios[k], fleet: true } });
      const l0 = await lpLambda(n, { scenario: { ...n.scenarios[k], fleet: false } });
      row.push(`${pct(l.lambda!)}${l.lambda! < l0.lambda! - 1e-6 ? " ⚓" : ""}`);
    }
    sweep.push(row);
  }
  csv("lp_fleet.csv", ["scenario", "ship_time_vs_2025", "share_of_fleet", "lambda_no_fleet", "lambda_fleet", "fleet"], fleetRows);
  L.push("## 1. Fleet constraint", "",
    `Ship-time available to the Asian trade = least ship-time that could have delivered the 2025 baseline × (1 + ${pct(NET.meta.fleet_slack!.value)} spare) = ${cap0.toFixed(0)} mtpa·days. The ships that carried the cargoes Asia can bid away from other buyers come with them (diverted mtpa × round trip to those buyers). "Ship-time needed" is the least needed to give every importer its equal-rationing share.`, "",
    md(["Scenario", "Ship-time needed vs 2025", "Share of available fleet", "λ without fleet limit", "λ with fleet limit", "Fleet"], fleetRows), "",
    "Sensitivity: λ with the fleet limit, by spare-fleet assumption (⚓ = ships, not gas, cut λ).", "",
    md(["Spare fleet", "Voyage times", "Hormuz closed", "Red Sea closed", "Malacca closed", "Hormuz + Red Sea"], sweep), "");

  // ---------------------------------------------------------------- 2. shadow prices
  const hz = NET.scenarios.hormuz;
  const lam = await lpLambda(NET, { scenario: hz });
  const groups = new Map<string, string[]>();
  for (const d of lam.duals) { const v = (100 * d.dual).toFixed(3); groups.set(v, [...(groups.get(v) ?? []), d.key]); }
  csv("lp_shadow_prices_hormuz.csv", ["constraint", "capacity_mtpa", "lambda_points_per_mtpa"], lam.duals.map((d) => [d.key, d.capacity, 100 * d.dual]));
  L.push("## 2. Shadow prices, Hormuz closed (equal-rationing LP)", "",
    "Value of one more mtpa of capacity, in percentage points of λ (the share every importer receives). Constraints not listed have zero value.", "",
    md(["Points of λ per mtpa", "Constraints"], [...groups.entries()].map(([v, ks]) => [v, ks.join(", ")])), "",
    "Every binding constraint is worth the same: in a pooled market one more tonne from any non-Gulf exporter, any pipeline or a partly reopened Hormuz raises everyone's share equally. Regas, storage rates and every other route have zero shadow price.", "");

  // ---------------------------------------------------------------- 3. dual-driven investment ranking
  const keyFor = (target: string) => {
    const [coll, id, field] = target.split(".");
    if (coll === "importers" && field === "regas") return `regas:${id}`;
    if (coll === "pipelines") return `pipeline:${id}`;
    if (coll === "exporters" && field === "asia_deliveries") return `supply:${id}`;
    if (coll === "routes") return `route:${id}`;
    return null;
  };
  const invRows: { label: string; firstOrder: number; exact: number; perMt: number }[] = [];
  for (const iv of NET.investments) {
    const fo = iv.changes.reduce((a, c) => { const k = keyFor(c.target); const d = lam.duals.find((x) => x.key === k)?.dual ?? 0; return a + d * c.delta; }, 0);
    const exact = (await lpLambda(applyChanges(NET, iv.changes), { scenario: hz })).lambda! - lam.lambda!;
    const size = iv.changes.reduce((a, c) => a + (/inventory|total_exports/.test(c.target) ? 0 : c.delta), 0);
    invRows.push({ label: iv.label, firstOrder: fo, exact, perMt: size > 0 ? exact / size : 0 });
  }
  invRows.sort((a, b) => b.firstOrder - a.firstOrder || b.exact - a.exact);
  csv("lp_investments.csv", ["investment", "dual_first_order_lambda_pts", "exact_lambda_pts", "pts_per_mtpa"], invRows.map((r) => [r.label, 100 * r.firstOrder, 100 * r.exact, 100 * r.perMt]));
  L.push("## 3. Investment ranking driven by shadow prices (Hormuz closed)", "",
    "First-order gain = shadow price × size of the investment. Exact = re-solving the LP with the investment. The two agree until an investment is large enough to close the gap.", "",
    md(["Investment", "Shadow-price estimate", "Exact gain in λ", "Per mtpa added"], invRows.map((r) => [r.label, `${(100 * r.firstOrder).toFixed(1)} pts`, `${(100 * r.exact).toFixed(1)} pts`, r.perMt ? `${(100 * r.perMt).toFixed(2)} pts` : "–"])), "",
    "Storage investments have no shadow price in the physical λ problem: they buy time (days of cover), not supply. See findings.md for their days-of-cover effect.", "");

  // ---------------------------------------------------------------- 4. selective passage
  const selective: [string, Scenario][] = [
    ["Hormuz closed", hz],
    ["Open only for Pakistan-bound cargoes (May 2026 arrangement)", NET.scenarios.hormuz_pakistan],
    ["Open only for UAE cargoes", { label: "uae only", hormuz: { origins: ["UAE"] } }],
    ["Open only for cargoes to China, India and Pakistan", { label: "friendly", hormuz: { destinations: ["CHN", "IND", "PAK"] } }],
    ["Open at 37% of normal (2026 average)", { label: "37", hormuz: { share: 0.37 } }],
  ];
  const selRows: (string | number)[][] = [];
  for (const [lbl, sc] of selective) {
    const v = await views(NET, sc);
    selRows.push([lbl, pct(v.lam), ...ORDER.map((id) => pct(v.rows.find((r) => r.id === id)!.priority))]);
  }
  csv("lp_selective_hormuz.csv", ["scenario", "lambda", ...ORDER.map((i) => `market_${i}`)], selRows);
  L.push("## 4. Selective passage through Hormuz", "",
    "Gulf cargoes are tagged by origin and destination (multi-commodity LP), so passage can depend on who ships or who buys. Columns show each importer's share of demand in the market order (Japan → Korea → Taiwan → China → Thailand → India → Bangladesh → Pakistan).", "",
    md(["Scenario", "λ", ...ORDER], selRows), "");

  // ---------------------------------------------------------------- 5. 2026 validation
  const sc26 = NET.scenarios.hormuz_2026;
  const v26 = await views(NET, sc26);
  const obs = Object.fromEntries((NET.validation_2026 as any[]).filter((v) => v.importer && v.value.unit === "%").map((v) => [v.importer, v]));
  const valRows = ORDER.filter((id) => obs[id]).map((id) => {
    const r = v26.rows.find((x) => x.id === id)!;
    const o = obs[id];
    return [name(id), `${sgn(o.value.value)} (${o.period})`, sgn(100 * (r.priority - 1)), sgn(100 * (r.rationed - 1)), `${sgn(100 * (r.last - 1))} to ${sgn(100 * (r.outbid - 1))}`];
  });
  const asia = (NET.validation_2026 as any[]).find((v) => v.id === "asia");
  csv("lp_validation_2026.csv", ["importer", "observed", "model_market", "model_rationed", "model_range"], valRows);
  L.push("## 5. Model vs 2026", "",
    `Scenario: Hormuz throughput at 37% of normal Gulf supply (IEA: Qatar + UAE delivered LNG −63% y-o-y, Jan–Oct 2026), fleet limit on. Model changes are vs 2025 import demand (LNG + pipeline); observed changes are LNG imports y-o-y and include January–February, before the closure.`, "",
    md(["Importer", "Observed LNG imports", "Model: market order", "Model: equal rationing", "Model range (last in line to outbid)"], valRows), "",
    `Asia overall: observed ${sgn(asia.value.value)} (${asia.period}); model equal-rationing ${sgn(100 * (v26.lam - 1))}.`, "",
    "Reading: the physical model gets the size of Asia's loss about right once Hormuz is partly open. The assumed market order gets Pakistan right and Bangladesh too harsh, and gets India, Thailand and China wrong: China, with pipelines, storage and coal, stepped back and resold cargoes, while India and Thailand bought more.", "");

  writeFileSync(join(OUT, "findings_lp.md"), L.join("\n"));
  console.log("wrote results/findings_lp.md and 5 LP CSVs");
}
main().catch((e) => { console.error(e); process.exit(1); });
